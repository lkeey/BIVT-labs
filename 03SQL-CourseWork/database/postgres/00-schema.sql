-- Public demonstration backend. The coursework's canonical database is SQL Server 2025.
-- Apply to a dedicated PostgreSQL 16+ database with pgvector available.
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA IF NOT EXISTS auth;
CREATE SCHEMA IF NOT EXISTS social;
CREATE SCHEMA IF NOT EXISTS knowledge;
CREATE SCHEMA IF NOT EXISTS assistant;
CREATE SCHEMA IF NOT EXISTS ops;

CREATE TABLE IF NOT EXISTS auth.useraccount (
  userid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login varchar(80) NOT NULL UNIQUE,
  emailnormalized varchar(254) NOT NULL UNIQUE,
  passwordhash bytea,
  accountstatus varchar(12) NOT NULL DEFAULT 'ACTIVE' CHECK (accountstatus IN ('ACTIVE','BLOCKED','DELETED')),
  createdat timestamptz NOT NULL DEFAULT now(),
  updatedat timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS auth.userprofile (
  userid bigint PRIMARY KEY REFERENCES auth.useraccount(userid),
  displayname varchar(120) NOT NULL,
  bio varchar(1000),
  profilevisibility varchar(8) NOT NULL DEFAULT 'PUBLIC' CHECK (profilevisibility IN ('PUBLIC','PRIVATE')),
  updatedat timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS auth.externalidentity (
  firebaseuid varchar(128) PRIMARY KEY CHECK (length(firebaseuid) BETWEEN 1 AND 128),
  userid bigint NOT NULL UNIQUE REFERENCES auth.useraccount(userid),
  createdat timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS social.community (
  communityid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owneruserid bigint NOT NULL REFERENCES auth.useraccount(userid),
  slug varchar(100) NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9-]{3,100}$'),
  communityname varchar(160) NOT NULL,
  description varchar(1000),
  visibility varchar(8) NOT NULL DEFAULT 'PUBLIC' CHECK (visibility IN ('PUBLIC','PRIVATE')),
  status varchar(12) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','ARCHIVED')),
  createdat timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS social.contentitem (
  contentid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind varchar(8) NOT NULL CHECK (kind IN ('POST','COMMENT','DOCUMENT')),
  contentstatus varchar(12) NOT NULL DEFAULT 'DRAFT' CHECK (contentstatus IN ('DRAFT','PUBLISHED','HIDDEN','DELETED')),
  allowrag boolean NOT NULL DEFAULT true,
  createdat timestamptz NOT NULL DEFAULT now(),
  updatedat timestamptz NOT NULL DEFAULT now(),
  publishedat timestamptz,
  CHECK (contentstatus <> 'PUBLISHED' OR publishedat IS NOT NULL)
);

-- SQL Graph NODE/EDGE becomes foreign-key-backed adjacency tables in PostgreSQL.
CREATE TABLE IF NOT EXISTS social.follows (
  followeruserid bigint NOT NULL REFERENCES auth.useraccount(userid),
  followeduserid bigint NOT NULL REFERENCES auth.useraccount(userid),
  createdat timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (followeruserid,followeduserid),
  CHECK (followeruserid <> followeduserid)
);
CREATE TABLE IF NOT EXISTS social.memberof (
  membershipid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  userid bigint NOT NULL REFERENCES auth.useraccount(userid),
  communityid bigint NOT NULL REFERENCES social.community(communityid),
  memberstatus varchar(8) NOT NULL DEFAULT 'PENDING' CHECK (memberstatus IN ('PENDING','ACTIVE','BLOCKED','REJECTED','BANNED','LEFT')),
  role varchar(10) NOT NULL DEFAULT 'MEMBER' CHECK (role IN ('OWNER','ADMIN','MODERATOR','MEMBER')),
  joinedat timestamptz NOT NULL DEFAULT now(),
  endedat timestamptz,
  CHECK (endedat IS NULL OR endedat >= joinedat),
  CHECK (memberstatus <> 'ACTIVE' OR endedat IS NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_memberof_current ON social.memberof(userid,communityid) WHERE endedat IS NULL;
CREATE INDEX IF NOT EXISTS ix_memberof_community_status ON social.memberof(communityid,memberstatus,userid);
CREATE TABLE IF NOT EXISTS social.authored (
  userid bigint NOT NULL REFERENCES auth.useraccount(userid),
  contentid bigint NOT NULL UNIQUE REFERENCES social.contentitem(contentid),
  createdat timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (userid,contentid)
);
CREATE TABLE IF NOT EXISTS social.publishedin (
  contentid bigint PRIMARY KEY REFERENCES social.contentitem(contentid),
  communityid bigint NOT NULL REFERENCES social.community(communityid),
  createdat timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_publishedin_community ON social.publishedin(communityid,contentid);
CREATE TABLE IF NOT EXISTS social.commenton (
  commentcontentid bigint PRIMARY KEY REFERENCES social.contentitem(contentid),
  postcontentid bigint NOT NULL REFERENCES social.contentitem(contentid),
  createdat timestamptz NOT NULL DEFAULT now(),
  CHECK (commentcontentid <> postcontentid)
);
CREATE INDEX IF NOT EXISTS ix_commenton_post ON social.commenton(postcontentid,commentcontentid);
CREATE TABLE IF NOT EXISTS social.reactto (
  userid bigint NOT NULL REFERENCES auth.useraccount(userid),
  contentid bigint NOT NULL REFERENCES social.contentitem(contentid),
  reactiontype varchar(12) NOT NULL CHECK (reactiontype IN ('LIKE','HELPFUL','INSIGHTFUL')),
  createdat timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (userid,contentid)
);

CREATE TABLE IF NOT EXISTS social.postrevision (
  revisionid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contentid bigint NOT NULL REFERENCES social.contentitem(contentid),
  revisionno integer NOT NULL CHECK (revisionno > 0),
  body text NOT NULL CHECK (length(body) > 0),
  contenthash bytea NOT NULL CHECK (octet_length(contenthash)=32),
  editedbyuserid bigint NOT NULL REFERENCES auth.useraccount(userid),
  iscurrent boolean NOT NULL DEFAULT true,
  changedat timestamptz NOT NULL DEFAULT now(),
  UNIQUE (contentid,revisionno), UNIQUE (contentid,revisionid)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_postrevision_current ON social.postrevision(contentid) WHERE iscurrent;
CREATE TABLE IF NOT EXISTS social.commentrevision (
  revisionid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contentid bigint NOT NULL REFERENCES social.contentitem(contentid),
  revisionno integer NOT NULL CHECK (revisionno > 0),
  body text NOT NULL CHECK (length(body) > 0),
  commentstatus varchar(8) NOT NULL DEFAULT 'VISIBLE' CHECK (commentstatus IN ('VISIBLE','HIDDEN','DELETED')),
  iscurrent boolean NOT NULL DEFAULT true,
  changedat timestamptz NOT NULL DEFAULT now(),
  UNIQUE (contentid,revisionno), UNIQUE (contentid,revisionid)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_commentrevision_current ON social.commentrevision(contentid) WHERE iscurrent;
CREATE TABLE IF NOT EXISTS social.documentdetail (
  contentid bigint PRIMARY KEY REFERENCES social.contentitem(contentid),
  title varchar(250) NOT NULL,
  description varchar(2000),
  documentstatus varchar(12) NOT NULL DEFAULT 'PROCESSING' CHECK (documentstatus IN ('PROCESSING','READY','FAILED'))
);
CREATE TABLE IF NOT EXISTS knowledge.documentversion (
  documentversionid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contentid bigint NOT NULL REFERENCES social.documentdetail(contentid),
  versionno integer NOT NULL CHECK (versionno > 0),
  filename varchar(260),
  mimetype varchar(127) NOT NULL CHECK (mimetype IN ('text/plain','application/pdf','application/vnd.openxmlformats-officedocument.wordprocessingml.document')),
  filebytes bytea,
  plaintext text,
  sizebytes bigint NOT NULL CHECK (sizebytes BETWEEN 1 AND 10485760),
  sha256 bytea NOT NULL CHECK (octet_length(sha256)=32),
  iscurrent boolean NOT NULL DEFAULT true,
  uploadstatus varchar(8) NOT NULL DEFAULT 'STORED' CHECK (uploadstatus IN ('STORED','FAILED')),
  ocrstatus varchar(10) NOT NULL DEFAULT 'PENDING' CHECK (ocrstatus IN ('PENDING','COMPLETED','NOT_NEEDED','FAILED')),
  ocrengineversion varchar(80),
  createdat timestamptz NOT NULL DEFAULT now(),
  UNIQUE (contentid,versionno), UNIQUE (contentid,documentversionid),
  CHECK ((mimetype='text/plain' AND plaintext IS NOT NULL AND filebytes IS NULL)
      OR (mimetype<>'text/plain' AND filebytes IS NOT NULL AND plaintext IS NULL AND filename IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_documentversion_current ON knowledge.documentversion(contentid) WHERE iscurrent;
CREATE TABLE IF NOT EXISTS knowledge.sourcerevision (
  sourcerevisionid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contentid bigint NOT NULL REFERENCES social.contentitem(contentid),
  postrevisionid bigint,
  commentrevisionid bigint,
  documentversionid bigint,
  iscurrent boolean NOT NULL DEFAULT true,
  processingstatus varchar(10) NOT NULL DEFAULT 'PENDING' CHECK (processingstatus IN ('PENDING','READY','FAILED')),
  extractedtext text,
  texthash bytea CHECK (texthash IS NULL OR octet_length(texthash)=32),
  createdat timestamptz NOT NULL DEFAULT now(),
  processedat timestamptz,
  FOREIGN KEY (contentid,postrevisionid) REFERENCES social.postrevision(contentid,revisionid),
  FOREIGN KEY (contentid,commentrevisionid) REFERENCES social.commentrevision(contentid,revisionid),
  FOREIGN KEY (contentid,documentversionid) REFERENCES knowledge.documentversion(contentid,documentversionid),
  CHECK (num_nonnulls(postrevisionid,commentrevisionid,documentversionid)=1),
  CHECK (processingstatus <> 'READY' OR (extractedtext IS NOT NULL AND texthash IS NOT NULL AND processedat IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_sourcerevision_current ON knowledge.sourcerevision(contentid) WHERE iscurrent;
CREATE TABLE IF NOT EXISTS knowledge.chunk (
  chunkid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sourcerevisionid bigint NOT NULL REFERENCES knowledge.sourcerevision(sourcerevisionid),
  chunkno integer NOT NULL CHECK (chunkno>0),
  chunktext text NOT NULL CHECK (length(chunktext)>0),
  pageno integer CHECK (pageno IS NULL OR pageno>0),
  startoffset integer NOT NULL CHECK (startoffset>=0),
  endoffset integer NOT NULL,
  chunkhash bytea NOT NULL CHECK (octet_length(chunkhash)=32),
  chunkstatus varchar(8) NOT NULL DEFAULT 'READY' CHECK (chunkstatus IN ('READY','STALE')),
  createdat timestamptz NOT NULL DEFAULT now(),
  UNIQUE (sourcerevisionid,chunkno), CHECK (endoffset>startoffset)
);
