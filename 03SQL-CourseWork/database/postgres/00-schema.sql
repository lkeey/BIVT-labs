CREATE TABLE IF NOT EXISTS knowledge.knowledgeentity (
  entityid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entitytype varchar(14) NOT NULL CHECK (entitytype IN ('TOPIC','PERSON','ORGANIZATION','EVENT','PLACE')),
  entityname varchar(500) NOT NULL,
  extractorversion varchar(80) NOT NULL,
  createdat timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS knowledge.mentions (
  mentionid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chunkid bigint NOT NULL REFERENCES knowledge.chunk(chunkid) ON DELETE CASCADE,
  entityid bigint NOT NULL REFERENCES knowledge.knowledgeentity(entityid) ON DELETE CASCADE,
  evidencechunkid bigint NOT NULL REFERENCES knowledge.chunk(chunkid) ON DELETE CASCADE,
  startoffset integer NOT NULL CHECK (startoffset>=0),
  endoffset integer NOT NULL CHECK (endoffset>startoffset),
  evidencetext varchar(1000) NOT NULL,
  confidence numeric(4,3) NOT NULL CHECK (confidence BETWEEN 0 AND 1),
  extractorversion varchar(80) NOT NULL,
  extractedat timestamptz NOT NULL DEFAULT now(),
  CHECK (evidencechunkid=chunkid)
);
CREATE TABLE IF NOT EXISTS knowledge.entityrelation (
  relationid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fromentityid bigint NOT NULL REFERENCES knowledge.knowledgeentity(entityid) ON DELETE CASCADE,
  toentityid bigint NOT NULL REFERENCES knowledge.knowledgeentity(entityid) ON DELETE CASCADE,
  predicatecode varchar(20) NOT NULL CHECK (predicatecode IN ('PARTICIPATES_IN','WORKS_AT','TAKES_PLACE_IN','RELATED_TO')),
  evidencechunkid bigint NOT NULL REFERENCES knowledge.chunk(chunkid) ON DELETE CASCADE,
  startoffset integer NOT NULL CHECK (startoffset>=0),
  endoffset integer NOT NULL CHECK (endoffset>startoffset),
  evidencetext varchar(1000) NOT NULL,
  confidence numeric(4,3) NOT NULL CHECK (confidence BETWEEN 0 AND 1),
  extractorversion varchar(80) NOT NULL,
  extractedat timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_mentions_entity_chunk ON knowledge.mentions(entityid,chunkid);
CREATE INDEX IF NOT EXISTS ix_entityrelation_from ON knowledge.entityrelation(fromentityid,evidencechunkid);
CREATE INDEX IF NOT EXISTS ix_entityrelation_to ON knowledge.entityrelation(toentityid,evidencechunkid);

CREATE TABLE IF NOT EXISTS assistant.ragsession (
  sessionid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  userid bigint NOT NULL REFERENCES auth.useraccount(userid),
  scope varchar(16) NOT NULL DEFAULT 'AllAccessible' CHECK (scope IN ('AllAccessible','Community')),
  communityid bigint REFERENCES social.community(communityid),
  createdat timestamptz NOT NULL DEFAULT now(),
  CHECK ((scope='AllAccessible' AND communityid IS NULL) OR (scope='Community' AND communityid IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS assistant.ragturn (
  turnid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sessionid bigint NOT NULL REFERENCES assistant.ragsession(sessionid),
  turnno integer NOT NULL CHECK (turnno>0),
  questiontext varchar(2000) NOT NULL,
  answertext text,
  answermodel varchar(120),
  generationstatus varchar(12) NOT NULL DEFAULT 'PENDING' CHECK (generationstatus IN ('PENDING','COMPLETED','FAILED','NO_SOURCES')),
  createdat timestamptz NOT NULL DEFAULT now(),
  completedat timestamptz,
  UNIQUE (sessionid,turnno)
);
CREATE TABLE IF NOT EXISTS assistant.retrievalrun (
  retrievalrunid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turnid bigint NOT NULL REFERENCES assistant.ragturn(turnid),
  retrievalmode varchar(16) NOT NULL DEFAULT 'HYBRID_GRAPH' CHECK (retrievalmode IN ('HYBRID_GRAPH','VECTOR','FULLTEXT')),
  accesspolicyversion varchar(40) NOT NULL DEFAULT '1',
  modelversion varchar(120) NOT NULL,
  createdat timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS assistant.retrievedchunk (
  retrievalrunid bigint NOT NULL REFERENCES assistant.retrievalrun(retrievalrunid),
  chunkid bigint NOT NULL REFERENCES knowledge.chunk(chunkid),
  rank integer NOT NULL CHECK (rank>0),
  vectorscore numeric(9,6),
  textscore numeric(9,6),
  graphscore numeric(9,6),
  snippet varchar(1000) NOT NULL,
  PRIMARY KEY (retrievalrunid,chunkid), UNIQUE (retrievalrunid,rank)
);
CREATE TABLE IF NOT EXISTS assistant.answercitation (
  citationid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  retrievalrunid bigint NOT NULL,
  chunkid bigint NOT NULL,
  quotetext varchar(1000) NOT NULL,
  pageno integer CHECK (pageno IS NULL OR pageno>0),
  startoffset integer NOT NULL CHECK (startoffset>=0),
  endoffset integer NOT NULL CHECK (endoffset>startoffset),
  FOREIGN KEY (retrievalrunid,chunkid) REFERENCES assistant.retrievedchunk(retrievalrunid,chunkid)
);
CREATE TABLE IF NOT EXISTS assistant.turnfeedback (
  turnid bigint PRIMARY KEY REFERENCES assistant.ragturn(turnid),
  userid bigint NOT NULL REFERENCES auth.useraccount(userid),
  rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment varchar(1000),
  submittedat timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS assistant.recommendationbatch (
  batchid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  userid bigint NOT NULL REFERENCES auth.useraccount(userid),
  algorithmversion varchar(40) NOT NULL,
  createdat timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS assistant.recommendationitem (
  batchid bigint NOT NULL REFERENCES assistant.recommendationbatch(batchid),
  contentid bigint NOT NULL REFERENCES social.contentitem(contentid),
  rank integer NOT NULL CHECK (rank>0),
  score numeric(9,6) NOT NULL CHECK (score BETWEEN 0 AND 1),
  reasoncode varchar(24) NOT NULL CHECK (reasoncode IN ('RELATED_TOPIC','FOLLOWED_AUTHOR','MEMBER_COMMUNITY','SIMILAR_INTEREST','POPULAR','FRESH')),
  reasontext varchar(500) NOT NULL,
  PRIMARY KEY (batchid,contentid), UNIQUE (batchid,rank)
);
CREATE TABLE IF NOT EXISTS ops.indexoutbox (
  eventid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sourcerevisionid bigint NOT NULL REFERENCES knowledge.sourcerevision(sourcerevisionid),
  modelid integer REFERENCES knowledge.embeddingmodel(modelid),
  operation varchar(8) NOT NULL CHECK (operation IN ('UPSERT','DELETE')),
  eventstatus varchar(8) NOT NULL DEFAULT 'PENDING' CHECK (eventstatus IN ('PENDING','CLAIMED','DONE','FAILED')),
  attemptcount integer NOT NULL DEFAULT 0 CHECK (attemptcount>=0),
  createdat timestamptz NOT NULL DEFAULT now(),
  claimedat timestamptz,
  claimtoken uuid,
  leaseuntil timestamptz,
  processedat timestamptz,
  lasterror varchar(2000),
  CHECK ((eventstatus='CLAIMED')=(claimtoken IS NOT NULL)),
  CHECK (leaseuntil IS NULL OR claimedat IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_indexoutbox_open ON ops.indexoutbox(sourcerevisionid,operation) WHERE eventstatus IN ('PENDING','CLAIMED');
CREATE INDEX IF NOT EXISTS ix_indexoutbox_claim ON ops.indexoutbox(eventstatus,eventid);
CREATE TABLE IF NOT EXISTS ops.auditevent (
  auditeventid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
